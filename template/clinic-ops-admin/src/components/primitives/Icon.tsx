export function Icon({ name, size = 16, className }: { name: string; size?: number; className?: string }) {
  const C = ICONS[name] ?? Circle;
  // absoluteStrokeWidth: every icon has the same 1.6px line weight whatever its size (12/14/16px) — one consistent family
  return <C size={size} strokeWidth={1.6} absoluteStrokeWidth aria-hidden="true" className={className} focusable={false} />;
}
