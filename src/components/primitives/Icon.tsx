/** Line weight for every icon in the app (light, not bold). */
export const ICON_STROKE = 1.0;

export function Icon({
  name,
  size = 16,
  className,
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const C = ICONS[name] ?? Circle;
  // absoluteStrokeWidth: every icon has the same light 1.25px line weight whatever its size (12/14/16/20px) — one consistent family
  return (
    <C
      size={size}
      strokeWidth={ICON_STROKE}
      absoluteStrokeWidth
      aria-hidden="true"
      className={className}
      focusable={false}
    />
  );
}
